// The logic of `pnpm gen:agent-docs` (scripts/gen-os-agent-docs.ts): which
// files of docs/agents/ are the code's defaults of Startup OS's own agents, and
// the module that carries their text into Convex. Pure.

/** run.md first (the rules every agent shares), then each agent's own file. */
export const OS_AGENT_DOC_FILES = ["run.md", "engineering.md", "sales.md", "finance.md", "chief-of-staff.md"] as const;
export type OsAgentDocFile = (typeof OS_AGENT_DOC_FILES)[number];

/** The module's text: each file's text as a string literal, in a fixed order. */
export function renderDocsModule(texts: Record<string, string>): string {
  const entries = OS_AGENT_DOC_FILES.map((file) => {
    const text = texts[file];
    if (text === undefined) throw new Error(`docs/agents/${file} was not read.`);
    return `  ${JSON.stringify(file)}: ${JSON.stringify(text)},`;
  });
  return [
    "// Generated by `pnpm gen:agent-docs` (scripts/gen-os-agent-docs.ts) from docs/agents/.",
    "// Do not edit: change the file in docs/agents/ and run it again. The text of",
    "// run.md and of each of the four agents' files: the code's defaults of Startup",
    "// OS's own agents (convex/lib/osAgentDefaults.ts). convex/osAgentDefaults.test.ts",
    "// fails when this and the files differ.",
    "//",
    "// Runs only inside Convex: never import it from the UI.",
    "",
    "export const OS_AGENT_DOCS = {",
    ...entries,
    "} as const;",
    "",
  ].join("\n");
}
